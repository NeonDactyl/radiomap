# Generous but meaningful: real error tops out at 5.6%, seen only at the
# sparsest part of the table's own distance grid (see module docstring).
MAX_ALLOWED_ERROR_PCT = 8.0


def _our_crossing_distance_km(erp_kw: float, haat_m: float, threshold_dbu: float) -> float:
    lo, hi = 0.5, 350.0
    for _ in range(60):
        mid = (lo + hi) / 2
        field_strength = fcc_curves.field_strength_dbu_per_kw(mid, haat_m) + 10 * math.log10(erp_kw)
        if field_strength > threshold_dbu:
            lo = mid
        else:
            hi = mid
    return lo


def test_bilinear_interpolation_matches_real_akima_within_tolerance():
    worst_pct = 0.0
    worst_case = None
    failures = []

    for erp_kw, haat_m, threshold_dbu, reference_km in REFERENCE_POINTS:
        ours_km = _our_crossing_distance_km(erp_kw, haat_m, threshold_dbu)
        pct_error = abs(ours_km - reference_km) / reference_km * 100

        if pct_error > worst_pct:
            worst_pct = pct_error
            worst_case = (erp_kw, haat_m, threshold_dbu, ours_km, reference_km)
        if pct_error > MAX_ALLOWED_ERROR_PCT:
            failures.append((erp_kw, haat_m, threshold_dbu, ours_km, reference_km, pct_error))

    assert not failures, (
        f"{len(failures)} point(s) exceeded {MAX_ALLOWED_ERROR_PCT}% error vs. the real FCC curve: {failures}"
    )
    assert worst_case is not None
    # Sanity check that this test is actually discriminating -- if this
    # ever reports ~0% for everything, the comparison itself is broken.
    assert worst_pct > 0.01, "suspiciously perfect match; check the comparison isn't a no-op"


def test_individual_kcfn_reference_point():
    """Pin the exact real-world case that was manually verified during
    this session: KCFN-FM (Wichita, KS -- flat terrain, 100kW, 148m HAAT).
    """
    ours_km = _our_crossing_distance_km(100.0, 148.0, 50.0)
    reference_km = 81.3439
    assert abs(ours_km - reference_km) / reference_km < 0.02  # verified well under 1% in this session
